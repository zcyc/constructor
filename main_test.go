func TestDefaultOutputFileIgnoresMarkerLookalikeComments(t *testing.T) {
	dir := t.TempDir()
	source := filepath.Join(dir, "types.go")
	if err := os.WriteFile(source, []byte("package test\n"), 0644); err != nil {
		t.Fatal(err)
	}
	content := "package test\n\n// Code generated by constructor. DO NOT EDIT.\n// func NewBox() *Box { return nil }\n\nconst marker = true\n"
	if err := os.WriteFile(filepath.Join(dir, "box_gen.go"), []byte(content), 0644); err != nil {
		t.Fatal(err)
	}
	want := filepath.Join(dir, "box2_gen.go")
	if got := defaultOutputFile(source, "Box"); got != want {
		t.Fatalf("comment lookalike output = %q, want %q", got, want)
	}
}
